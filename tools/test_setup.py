"""Windows setup integration checks with synthetic PK3 fixtures, no game data."""
from pathlib import Path
import json
import os
import shutil
import struct
import subprocess
import unittest
import uuid
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKS = ("pak0.pk3", "pak1_large.pk3", "pak2.pk3", "pak3.pk3", "pak4_english.pk3", "pak5_mod.pk3")
TEST_ROOT = ROOT / "private" / ("setup-tests-" + uuid.uuid4().hex)


def setup_environment():
    return {key: value for key, value in os.environ.items()
            if not key.upper().startswith("LG_SETUP_")}


def make_language(path, word):
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as pack:
        if word == "Terug":
            pack.writestr("ui/main.urc", 'title "Terug"\n')
        else:
            pack.writestr("dialog/standard.tlk", ('TALK\n"sound/character/cheshire_cat/vo/cat037.wav"\n' + word + '\n').encode("cp1252"))


def make_data(root, version=42):
    base = root / "Alice1" / "bin" / "base"
    base.mkdir(parents=True)
    for index, name in enumerate(PACKS):
        with zipfile.ZipFile(base / name, "w", zipfile.ZIP_DEFLATED) as pack:
            pack.writestr("synthetic-fixture.txt", "Not original game data")
            if name == "pak4_english.pk3":
                pack.writestr("dialog/standard.tlk", 'TALK\n"sound/character/cheshire_cat/vo/cat037.wav"\nEvery adventure requires a first step.\n')
            if index == 0:
                header = b"FAKK" + struct.pack("<i", version)
                pack.writestr("maps/gvillage.bsp", header)
                for i in range(35):
                    pack.writestr(f"maps/synthetic{i}.bsp", header)
    return base


@unittest.skipUnless(os.name == "nt", "Setup.cmd is a Windows entry point")
class SetupTests(unittest.TestCase):
    def setUp(self):
        self.root = TEST_ROOT / self._testMethodName
        self.app = self.root / "Looking Glass & preview [test]"
        self.app.mkdir(parents=True)
        shutil.copyfile(ROOT / "Setup.cmd", self.app / "Setup.cmd")
        self.data = self.root / "Données & game [test]"
        self.base = make_data(self.data)

    def run_setup(self, source, expected=0, language=None, cancel=None, action="setup"):
        # Paths are generated by these fixtures (no quotes/newlines/percent signs).
        # Pass them as literal quoted CMD arguments, never interpolate into PS code.
        command = f'"{os.environ["COMSPEC"]}" /d /s /c ""{self.app / "Setup.cmd"}" "{source}" --no-pause"'
        env = setup_environment()
        env["LG_SETUP_ACTION"] = action
        if language: env["LG_SETUP_LANGUAGE"] = language
        if cancel: env["LG_SETUP_CANCEL"] = str(cancel)
        result = subprocess.run(command, cwd=self.app, env=env, capture_output=True, timeout=60)
        self.assertEqual(result.returncode, expected, result.stdout.decode(errors="replace") + result.stderr.decode(errors="replace"))
        return result

    def saved_path(self):
        return (self.app / "private/data-path.txt").read_text(encoding="utf-8").strip()

    def installed_state(self):
        paths = [self.app / "private/data-path.txt", self.app / "private/setup.json"]
        paths.extend((self.app / self.saved_path()).glob("*.pk3"))
        save = self.app / "private/saves/keep.txt"
        paths.append(save)
        return {path: path.read_bytes() for path in paths}

    def create_save(self):
        save = self.app / "private/saves/keep.txt"
        save.parent.mkdir(parents=True, exist_ok=True)
        save.write_text("preserve my progress")

    def test_folder_with_spaces_unicode_and_metacharacters(self):
        self.run_setup(self.data)
        imported = self.app / self.saved_path()
        self.assertTrue(imported.is_relative_to(self.app / "private/game-data"))
        self.assertEqual((imported / "pak0.pk3").read_bytes(), (self.base / "pak0.pk3").read_bytes())
        self.assertTrue((self.base / "pak0.pk3").is_file())
        receipt = json.loads((self.app / "private/setup.json").read_text(encoding="utf-8"))
        self.assertIsNone(receipt["archiveSha256"])

    def test_failure_preserves_configuration_and_saves(self):
        self.run_setup(self.data)
        before = self.saved_path()
        save = self.app / "private/saves/user-save.txt"
        save.parent.mkdir()
        save.write_text("preserve my save")
        self.run_setup(self.root / "missing.7z", expected=1)
        self.assertEqual(self.saved_path(), before)
        self.assertEqual(save.read_text(), "preserve my save")

    def test_wrong_map_format_is_rejected(self):
        invalid = self.root / "wrong version"
        make_data(invalid, version=41)
        self.run_setup(invalid, expected=1)
        self.assertFalse((self.app / "private/data-path.txt").exists())

    def test_corrupt_pack_is_rejected(self):
        (self.base / "pak3.pk3").write_bytes(b"not a zip")
        self.run_setup(self.data, expected=1)
        self.assertFalse((self.app / "private/data-path.txt").exists())

    def test_relative_location_and_automatic_discovery(self):
        internal = self.app / "alice_202106"
        base = make_data(internal)
        self.run_setup("")
        self.assertTrue((self.app / self.saved_path() / "pak0.pk3").is_file())

    def test_languages_use_one_word_and_switch_without_source_changes(self):
        words = {"nl": "Terug", "de": "Schritt", "fr": "pas", "es": "paso"}
        files = {"de": "pak4_german.pk3", "fr": "pak4_french.pk3", "es": "pak4_spanish.pk3", "nl": "pak4_dutch.pk3"}
        for code, word in words.items():
            make_language(self.base / files[code], word)
        (self.base / "z_custom_mod.pk3").write_bytes((self.base / "pak2.pk3").read_bytes())
        original = {p.name: p.read_bytes() for p in self.base.iterdir()}
        self.run_setup(self.data, language="en")
        active = self.app / self.saved_path()
        english_stamp = (active / "pak4_english.pk3").stat().st_mtime_ns
        for code in words:
            self.run_setup("", language=code, action="language")
            expected = [files[code]] + (["pak4_english.pk3"] if code == "nl" else [])
            self.assertEqual(sorted(p.name for p in active.glob("pak4_*.pk3")), sorted(expected))
            self.assertEqual((active / files[code]).read_bytes(), original[files[code]])
            if code == "nl":
                self.assertEqual((active / "pak4_english.pk3").stat().st_mtime_ns, english_stamp)
                self.assertEqual((active / "pak4_english.pk3").read_bytes(), original["pak4_english.pk3"])
        result = self.run_setup("", expected=1, language="es", action="language")
        self.assertIn(b"already active", result.stdout)
        self.run_setup("", language="nl", action="language")
        self.run_setup("", language="en", action="language")
        self.assertEqual([p.name for p in active.glob("pak4_*.pk3")], ["pak4_english.pk3"])
        cache = self.app / "private/game-data/languages"
        for name in files.values():
            self.assertEqual((cache / name).read_bytes(), original[name])
        for name, data in original.items():
            self.assertEqual((self.base / name).read_bytes(), data)
            if name not in files.values():
                self.assertEqual((active / name).read_bytes(), data)

    def test_wrong_language_keeps_active_pack_and_pointer(self):
        german = self.base / "pak4_german.pk3"
        make_language(german, "Schritt")
        self.run_setup(self.data, language="de")
        self.create_save()
        before = self.installed_state()
        source = self.root / "wrong-language"
        wrong = source / "pak4_french.pk3"
        make_language(wrong, "Terug")
        result = self.run_setup(source, expected=1, language="fr", action="language")
        self.assertIn(b"Language pack does not match fr", result.stdout)
        self.assertEqual(self.installed_state(), before)
        self.run_setup("", expected=1, language="es", action="language")
        self.assertEqual(self.installed_state(), before)

    def test_word_in_unrelated_text_does_not_validate_language(self):
        pack = self.base / "pak4_german.pk3"
        with zipfile.ZipFile(pack, "w") as z:
            z.writestr("dialog/standard.tlk", '// Schritt\n"sound/Schritt.wav"\npas\n')
        result = self.run_setup(self.data, expected=1, language="de")
        self.assertIn(b"Expected 'Schritt' in dialog/standard.tlk", result.stdout)
        self.assertFalse((self.app / "private/data-path.txt").exists())

    def test_zip_bundle_imports_languages_without_executables(self):
        make_language(self.base / "loc/base_g.pk3", "Schritt")
        archive = self.root / "bundle.zip"
        with zipfile.ZipFile(archive, "w") as z:
            for pack in self.base.rglob("*.pk3"):
                z.write(pack, pack.relative_to(self.data).as_posix())
            z.writestr("Alice1/bin/original.exe", b"not imported")
            z.writestr("Alice1/bin/base/../../escape.txt", b"not imported")
        self.run_setup(archive, language="de")
        active = self.app / self.saved_path()
        expected = (set(PACKS) - {"pak4_english.pk3"}) | {"pak4_german.pk3"}
        self.assertEqual(set(p.name for p in active.iterdir()), expected)
        cache = self.app / "private/game-data/languages"
        self.assertEqual((cache / "pak4_english.pk3").read_bytes(), (self.base / "pak4_english.pk3").read_bytes())
        self.assertEqual((cache / "pak4_german.pk3").read_bytes(), (self.base / "loc/base_g.pk3").read_bytes())
        self.run_setup("", language="en", action="language")
        self.run_setup("", language="de", action="language")
        self.assertTrue((active / "pak4_german.pk3").exists())

    def test_failed_publish_restores_active_language(self):
        german = self.base / "pak4_german.pk3"
        make_language(german, "Schritt")
        self.run_setup(self.data, language="de")
        active = self.app / self.saved_path()
        self.create_save()
        before = self.installed_state()
        make_language(self.app / "private/game-data/languages/pak4_dutch.pk3", "Terug")
        backend = self.app / "Setup.cmd"
        text = backend.read_text(encoding="utf-8")
        marker = '        Save-Text $config ($savedPath'
        self.assertEqual(text.count(marker), 1)
        text = text.replace(marker, "        throw 'synthetic publish failure'\n" + marker)
        backend.write_text(text, encoding="utf-8")
        # Publishing configuration belongs to full setup, not language-only changes.
        result = self.run_setup(active, expected=1, language="nl")
        self.assertIn(b"synthetic publish failure", result.stdout)
        self.assertEqual(self.installed_state(), before)
        self.assertEqual((active / "pak4_german.pk3").read_bytes(), german.read_bytes())
        self.assertFalse((active / "pak4_dutch.pk3").exists())
        self.assertFalse((active / "pak4_english.pk3").exists())

    def test_standalone_pak_is_rejected_without_changing_installation(self):
        self.run_setup(self.data)
        self.create_save()
        before = self.installed_state()
        german = self.root / "anything.pk3"
        make_language(german, "Schritt")
        result = self.run_setup(german, expected=1)
        self.assertIn(b"Select a .7z or .zip archive", result.stdout)
        self.assertEqual(self.installed_state(), before)

    def test_cancel_keeps_installed_language(self):
        german = self.base / "pak4_german.pk3"
        make_language(german, "Schritt")
        self.run_setup(self.data, language="de")
        self.create_save()
        before = self.installed_state()
        cancel = self.root / "cancel"
        cancel.write_text("cancel")
        result = self.run_setup("", expected=1, language="en", cancel=cancel, action="language")
        self.assertIn(b"cancel", result.stdout.lower())
        self.assertEqual(self.installed_state(), before)

    def test_archive_extracts_only_data_and_reuses_import(self):
        extractor = shutil.which("7z") or shutil.which("7zz")
        if not extractor:
            candidate = Path(os.environ.get("ProgramFiles", "C:/Program Files")) / "7-Zip/7z.exe"
            extractor = str(candidate) if candidate.is_file() else None
        if not extractor:
            self.skipTest("7-Zip is needed for the archive extraction case")
        (self.data / "Alice1/bin/original.exe").write_bytes(b"must not be extracted")
        (self.data / "Alice1/bin/base/unwanted.cmd").write_text("must not be extracted")
        archive = self.root / "Alice1_2011_vanilla.7z"
        subprocess.run([extractor, "a", "-t7z", str(archive), "Alice1"], cwd=self.data, check=True, capture_output=True)
        self.run_setup(archive)
        before = self.saved_path()
        imported = self.app / before
        self.assertEqual(sorted(p.name for p in imported.iterdir()), sorted(PACKS))
        original = {p.name: p.read_bytes() for p in imported.iterdir()}
        self.run_setup(archive)
        self.assertEqual(self.saved_path(), before)
        self.assertEqual({p.name: p.read_bytes() for p in imported.iterdir()}, original)


if __name__ == "__main__":
    print(f"Synthetic setup fixtures stay in the ignored folder: {TEST_ROOT}")
    unittest.main()
